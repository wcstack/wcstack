const HARM_ORDER = Object.fromEntries(HARM.map((h, i) => [h, i]));
const cell = (s) => String(s).replace(/\|/g, "\\|").replace(/\r?\n/g, " ");
const lintCell = (e) => (lints(e).length === 0 ? "—" : lints(e).map((l) => `\`${l.code}\` (${l.severity})`).join(", "));

function render(lang) {
  const t = T[lang];
  const byLayer = { design: [], runtime: [], lint: [], docs: [] };
  for (const e of entries) byLayer[layerOf(e)].push(e);
  for (const list of Object.values(byLayer)) {
    list.sort((a, b) => HARM_ORDER[a.harm] - HARM_ORDER[b.harm] || a.id.localeCompare(b.id));
  }
  const out = [];
  out.push(`### ${t.summary}`, "", `| ${t.layer} | ${t.count} |`, "|---|---|");
  for (const layer of ["design", "runtime", "lint", "docs"]) out.push(`| ${t.layers[layer]} | ${byLayer[layer].length} |`);
  out.push(`| ${t.uncounted} | ${uncounted.length} |`, "");

  const section = (layer, head, row) => {
    out.push(`### ${t.sections[layer]}`, "");
    if (byLayer[layer].length === 0) {
      out.push(t.none, "");
      return;
    }
    out.push(`| ${head.join(" | ")} |`, `|${head.map(() => "---").join("|")}|`);
    for (const e of byLayer[layer]) out.push(`| ${row(e).map(cell).join(" | ")} |`);
    out.push("");
  };
  const c = t.cols;
  const withNote = (e, text) => (e.note ? `${text} ${e.note[lang]}` : text);
  const plan = (e) => {
    const labels = dispositions(e).map((d) => t.plan[d](e.breaking)).join(t.then);
    return e.note ? `${labels}${t.stop}${e.note[lang]}` : labels;
  };
  section("docs", [c.mistake, c.effect, c.harm, c.plan], (e) => [e.mistake[lang], e.effect[lang], t.harm[e.harm], plan(e)]);
  section("lint", [c.mistake, c.lint, c.effect, c.harm, c.plan], (e) => [e.mistake[lang], lintCell(e), e.effect[lang], t.harm[e.harm], plan(e)]);
  section("runtime", [c.mistake, c.reported, c.lint], (e) => [e.mistake[lang], withNote(e, `${t.runtime[e.runtime]}: ${e.effect[lang]}`), lintCell(e)]);
  section("design", [c.mistake, c.effect], (e) => [e.mistake[lang], withNote(e, e.effect[lang])]);

  out.push(`### ${t.uncounted}`, "", `| ${c.code} | ${c.why} |`, "|---|---|");
  for (const u of [...uncounted].sort((a, b) => a.code.localeCompare(b.code))) out.push(`| \`${u.code}\` | ${cell(u.why[lang])} |`);
  out.push("");
  return out;
}

const drift = [];
for (const [lang, file] of Object.entries(DOCS)) {
  if (!existsSync(file)) {
    problems.push(`${file}: missing`);
    continue;
  }
  const current = readFileSync(file, "utf8");
  const eol = current.includes("\r\n") ? "\r\n" : "\n";
  const start = current.indexOf(BEGIN);
  const end = current.indexOf(END);
  if (start < 0 || end < start) {
    problems.push(`${file}: the begin / end markers are missing`);
    continue;
  }
  const next = current.slice(0, start) + [BEGIN, "", ...render(lang), END].join(eol) + current.slice(end + END.length);
  if (next === current) continue;
  if (check) drift.push(file);
  else {
    writeFileSync(file, next);
    console.log(`updated ${file}`);
  }
}

// --- report ------------------------------------------------------------------

const counts = { design: 0, runtime: 0, lint: 0, docs: 0 };
for (const e of entries) counts[layerOf(e)]++;
console.log(
  `mistake catalogue: ${entries.length} entries — design ${counts.design}, runtime ${counts.runtime}, ` +
    `lint only ${counts.lint}, docs only ${counts.docs}; ${uncounted.length} lint codes not counted`,
);

if (problems.length > 0 || drift.length > 0) {
  if (problems.length > 0) console.error("mistake catalogue problems:\n  " + problems.join("\n  "));
  if (drift.length > 0) {
    console.error("mistake catalogue drift in:\n  " + drift.join("\n  ") + "\n\nRun `node scripts/sync-mistake-catalogue.mjs` and commit the result.");
  }
  process.exit(1);
}
